    fun t(lang: String, key: String): String {
        val table = when (lang) {
            "en" -> en
            "tr" -> tr
            else -> fa
        }
        return table[key] ?: fa[key] ?: key
    }

    fun isRtl(lang: String): Boolean = lang == "fa"

    fun error(e: Throwable, lang: String): String {
        if (e is ApiException && e.isNetwork) return t(lang, "connect_fail")
        if (e is IOException) return t(lang, "connect_fail")
        val msg = e.message.orEmpty()
        if (looksLikeSystemNetwork(msg)) return t(lang, "connect_fail")
        if (e is ApiException && msg.isNotBlank()) return msg
        return t(lang, "connect_fail")
    }

    private fun looksLikeSystemNetwork(raw: String): Boolean {
        val t = raw.lowercase()
        return t.contains("unable to resolve host") ||
            t.contains("no address associated") ||
            t.contains("failed to connect") ||
            t.contains("unknownhost") ||
            t.contains("timed out") ||
            t.contains("timeout") ||
            t.contains("connection reset") ||
            t.contains("network is unreachable") ||
            t.contains("software caused connection abort") ||
            t.contains("cleartext http traffic") ||
            t.contains("sslhandshake")
    }

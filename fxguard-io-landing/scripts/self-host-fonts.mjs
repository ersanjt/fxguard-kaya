#!/usr/bin/env node
/**
 * Self-host the storefront web fonts (SIL OFL) so visitors' IPs are not sent to
 * Google on every page view (KVKK m.9 cross-border transfer / GDPR).
 *
 *   node scripts/self-host-fonts.mjs          download fonts + write css/fonts.css
 *   node scripts/self-host-fonts.mjs --pages  also rewrite <link> tags in all pages
 */
import { mkdir, readFile, writeFile, readdir } from 'node:fs/promises';
import { join, dirname, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FONT_DIR = join(ROOT, 'fonts');
const CSS_OUT = join(ROOT, 'css', 'fonts.css');
const UA =
    'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';

const FAMILIES = [
    'Outfit:wght@400;500;600;700;800',
    'Vazirmatn:wght@300;400;500;600;700;800',
    'Noto+Sans+Arabic:wght@400;500;600;700',
    'Noto+Sans:wght@400;500;600;700',
    'Syne:wght@700;800;900',
    'DM+Sans:opsz,wght@9..40,300;9..40,400;9..40,500;9..40,600',
];

function slug(s) {
    return String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

async function buildFonts() {
    const url =
        'https://fonts.googleapis.com/css2?' + FAMILIES.map((f) => 'family=' + f).join('&') + '&display=swap';
    const res = await fetch(url, { headers: { 'User-Agent': UA } });
    if (!res.ok) throw new Error('Google Fonts CSS ' + res.status);
    const css = await res.text();
    await mkdir(FONT_DIR, { recursive: true });

    const blocks = css.split('/*').slice(1);
    const seen = new Map();
    let out =
        '/* Self-hosted web fonts (SIL Open Font License). Generated by scripts/self-host-fonts.mjs — do not edit. */\n';
    for (const block of blocks) {
        const subset = block.slice(0, block.indexOf('*/')).trim();
        const face = block.slice(block.indexOf('@font-face'));
        const family = (/font-family:\s*'([^']+)'/.exec(face) || [])[1];
        const src = (/url\((https:\/\/fonts\.gstatic\.com\/[^)]+\.woff2)\)/.exec(face) || [])[1];
        if (!family || !src) continue;
        let file = seen.get(src);
        if (!file) {
            file = slug(family) + '-' + slug(subset) + '-' + seen.size + '.woff2';
            const bin = await fetch(src, { headers: { 'User-Agent': UA } });
            if (!bin.ok) throw new Error('font ' + bin.status + ' ' + src);
            await writeFile(join(FONT_DIR, file), Buffer.from(await bin.arrayBuffer()));
            seen.set(src, file);
        }
        out += '/* ' + subset + ' */\n' + face.replace(src, '/fonts/' + file).trim() + '\n';
    }
    await writeFile(CSS_OUT, out);
    console.log('fonts: ' + seen.size + ' files, css/fonts.css written');
}

const GOOGLE_LINK_RE =
    /\s*<link rel="preconnect" href="https:\/\/fonts\.(googleapis|gstatic)\.com"( crossorigin)?>/g;
const GOOGLE_CSS_RE = /https:\/\/fonts\.googleapis\.com\/css2\?[^"']+/g;

async function* walk(dir) {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
        if (entry.name === 'node_modules' || entry.name === 'fonts' || entry.name.startsWith('.')) continue;
        const p = join(dir, entry.name);
        if (entry.isDirectory()) yield* walk(p);
        else if (['.html', '.mjs', '.js'].includes(extname(p)) && !p.endsWith('self-host-fonts.mjs')) yield p;
    }
}

async function rewritePages() {
    let changed = 0;
    for await (const file of walk(ROOT)) {
        const src = await readFile(file, 'utf8');
        const next = src.replace(GOOGLE_LINK_RE, '').replace(GOOGLE_CSS_RE, '/css/fonts.css?v=20261030a');
        if (next !== src) {
            await writeFile(file, next);
            changed++;
        }
    }
    console.log('pages rewritten: ' + changed);
}

await buildFonts();
if (process.argv.includes('--pages')) await rewritePages();
